"""Bundle one paste-able task, without dependencies on local repo files."""
import json
from pathlib import Path
HERE=Path(__file__).resolve().parent
parts=['# Generated by followup/build_task.py. No model calls on load.\n']
parts.append('CASES = '+repr(json.loads((HERE/'cases_followup.json').read_text()))+'\n')
for name in ('grading.py','metrics.py','runtime.py'):parts.append((HERE/name).read_text())
(HERE/'kaggle_followup.py').write_text('\n\n'.join(parts))
print('Built standalone followup/kaggle_followup.py')
